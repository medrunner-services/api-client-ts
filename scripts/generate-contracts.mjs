import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import openapiTS, { astToString } from "openapi-typescript";
import { compile as compileTypes } from "json-schema-to-typescript";

const directory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const document = JSON.parse(await readFile(path.join(directory, "openapi/openapi.json"), "utf8"));
const events = JSON.parse(await readFile(path.join(directory, "openapi/events.json"), "utf8"));
const ajv = new Ajv2020({ strict: false, allErrors: false, inlineRefs: false, loopRequired: 8, code: { source: true, esm: true }, validateFormats: true });
addFormats(ajv);
ajv.addSchema({ $id: "https://contracts.medrunner.invalid/http", components: document.components });
const exports = {};
const routes = [];
let sequence = 0;
const compiledSchemas = new Map();
function compile(schema) {
  const key = JSON.stringify(schema);
  if (compiledSchemas.has(key)) return compiledSchemas.get(key);
  const name = `contract${sequence++}`;
  const id = `https://contracts.medrunner.invalid/${name}`;
  const resolved = JSON.parse(JSON.stringify(schema).replaceAll('"#/components/', '"https://contracts.medrunner.invalid/http#/components/'));
  ajv.addSchema({ ...resolved, $id: id });
  exports[name] = id;
  compiledSchemas.set(key, name);
  return name;
}
for (const [url, item] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
    const responses = {};
    for (const [status, response] of Object.entries(operation.responses ?? {})) {
      if (!/^2\d\d$/.test(status)) continue;
      const schema = response.content?.["application/json"]?.schema;
      responses[status] = schema ? compile(schema) : null;
    }
    const request = operation.requestBody?.content?.["application/json"]?.schema;
    routes.push({ path: url, method: method.toUpperCase(), responses,
      request: request ? compile(request) : null, requestRequired: operation.requestBody?.required === true });
  }
}
const eventValidators = {};
for (const [name, schema] of Object.entries(events)) eventValidators[name] = compile(schema);
const generated = path.join(directory, "src/contracts/generated");
await mkdir(generated, { recursive: true });
// A fixed stdin source name keeps generated bytes identical across repeated builds.
await build({ stdin: { contents: standaloneCode(ajv, exports), sourcefile: "compiled-contracts.mjs", resolveDir: directory },
  outfile: path.join(generated, "validators.js"), bundle: true, format: "esm", platform: "browser", target: "es2022",
  banner: { js: "// Generated from the API contracts. Do not edit." }, logLevel: "silent" });
await writeFile(path.join(generated, "validators.d.ts"), Object.keys(exports).map(name =>
  `export declare const ${name}: { (value: unknown): boolean; errors?: { instancePath: string; keyword: string; params: Record<string, unknown> }[] | null };`).join("\n") + "\n");
routes.sort((a, b) => (a.path.match(/\{/g)?.length ?? 0) - (b.path.match(/\{/g)?.length ?? 0));
await writeFile(path.join(generated, "catalog.ts"), `// Generated from the API contracts. Do not edit.\nexport const routes = ${JSON.stringify(routes, null, 2)} as const;\nexport const eventValidators = ${JSON.stringify(eventValidators, null, 2)} as const;\n`);
await writeFile(path.join(generated, "wire.ts"), astToString(await openapiTS(document)));
console.log(`Generated ${sequence} validators for ${routes.length} HTTP operations and ${Object.keys(events).length} event models.`);

const definitions = Object.fromEntries(Object.entries(events).map(([name, schema]) => [name,
  JSON.parse(JSON.stringify(schema).replaceAll('"#/', `"#/definitions/${name}/`))]));
await writeFile(path.join(generated, "events.ts"), await compileTypes({
  type: "object", additionalProperties: false, definitions,
  properties: Object.fromEntries(Object.keys(events).map(name => [name, { $ref: `#/definitions/${name}` }])),
  required: Object.keys(events),
}, "EventPayloads", { bannerComment: "// Generated from the .NET event contracts. Do not edit.", unknownAny: true }));
